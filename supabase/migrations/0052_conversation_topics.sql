create table public.conversation_topic_history(pair_low uuid not null references public.profiles(id)on delete cascade,pair_high uuid not null references public.profiles(id)on delete cascade,topic_id integer not null references public.conversation_topics(id),picked_by uuid references public.profiles(id)on delete set null,picked_at timestamptz not null default clock_timestamp(),primary key(pair_low,pair_high,topic_id),check(pair_low<pair_high));
alter table public.conversation_topic_history enable row level security;
revoke all on public.conversation_topic_history from public,anon,authenticated;
grant all on public.conversation_topics,public.conversation_topic_history to service_role;
create function public.conversation_topic(p_next boolean default false)returns jsonb language plpgsql security definer set search_path=public as $$declare uid uuid:=auth.uid();friend uuid;lo uuid;hi uuid;chosen integer;body text;used integer;total integer;begin
 friend:=public.friend_id(uid);if uid is null or friend is null then raise insufficient_privilege;end if;lo:=least(uid,friend);hi:=greatest(uid,friend);
 perform pg_advisory_xact_lock(hashtextextended(lo::text||hi::text,73491));
 select count(*)into total from public.conversation_topics;
 if not p_next then select h.topic_id into chosen from public.conversation_topic_history h where pair_low=lo and pair_high=hi order by picked_at desc,topic_id desc limit 1;end if;
 if p_next then
 select t.id into chosen from public.conversation_topics t where not exists(select from public.conversation_topic_history h where h.pair_low=lo and h.pair_high=hi and h.topic_id=t.id)order by random()limit 1;
 if chosen is not null then insert into public.conversation_topic_history(pair_low,pair_high,topic_id,picked_by)values(lo,hi,chosen,uid);end if;
 end if;
 select count(*)into used from public.conversation_topic_history where pair_low=lo and pair_high=hi;
 if chosen is not null then select prompt into body from public.conversation_topics where id=chosen;end if;
 return jsonb_build_object('id',chosen,'prompt',body,'used',used,'total',total,'exhausted',used>=total);
end$$;
revoke all on function public.conversation_topic(boolean)from public,anon;grant execute on function public.conversation_topic(boolean)to authenticated;
